def apply_hardening_settings(settings: dict) -> tuple[bool, str]:
    """
    Generates NGINX hardening configuration (server_tokens) and stores whitelisted/blacklisted
    IPs dynamically in Redis to enable zero-reload IP blocking.
    """
    try:
        server_cloaking = settings.get("server_cloaking", True)
        ip_blacklist = settings.get("ip_blacklist", [])
        ip_whitelist = settings.get("ip_whitelist", [])
        ja4_blacklist = settings.get("ja4_blacklist", [])

        # 1. Update dynamic IP Whitelist/Blacklist in Redis
        r = get_redis_client()

        # Flush previous keys
        r.delete("waf:whitelist", "waf:whitelist:cidrs", "waf:blacklist", "waf:blacklist:cidrs", "waf:blacklist:ja4")
        
        # Add whitelist
        for ip in ip_whitelist:
            ip = ip.strip()
            if ip:
                if not _validate_ip_or_cidr(ip):
                    logger.warning(f"Skipping invalid IP/CIDR in whitelist: '{ip}'")
                    continue
                if "/" in ip:
                    r.sadd("waf:whitelist:cidrs", ip)
                else:
                    r.sadd("waf:whitelist", ip)

        # Add blacklist
        for ip in ip_blacklist:
            ip = ip.strip()
            if ip:
                if not _validate_ip_or_cidr(ip):
                    logger.warning(f"Skipping invalid IP/CIDR in blacklist: '{ip}'")
                    continue
                if "/" in ip:
                    r.sadd("waf:blacklist:cidrs", ip)
                else:
                    r.sadd("waf:blacklist", ip)

        # Add JA4 blacklist — exact-match only, a fingerprint has no CIDR
        # concept. Checked by ml_check.lua against the fingerprint ja4.lua
        # already cached per-connection during the TLS handshake; see that
        # file for why this is a single set rather than the IP list's
        # exact+CIDR+feed+auto tiers (no feed/auto source exists yet).
        for ja4 in ja4_blacklist:
            ja4 = ja4.strip().lower()
            if ja4:
                if not _validate_ja4(ja4):
                    logger.warning(f"Skipping invalid JA4 fingerprint in blacklist: '{ja4}'")
                    continue
                r.sadd("waf:blacklist:ja4", ja4)

        logger.info("Successfully updated dynamic WAF IP/JA4 whitelist/blacklist in Redis.")

        # 2. Write server_tokens configuration to files
        config_lines = [
            "# Auto-generated by CyberSentinel WAF GUI",
            "# Do not edit manually",
            "",
        ]

        if server_cloaking:
            config_lines.append("server_tokens off;")
        else:
            config_lines.append("server_tokens on;")

        config_lines.append("")
        config_content = "\n".join(config_lines) + "\n"

        # Check if config content changed before writing and reloading to achieve zero-reload IP blocking
        existing_content = ""
        if os.path.exists(HARDENING_CONF_PATH):
            with open(HARDENING_CONF_PATH, "r", encoding="utf-8") as f:
                existing_content = f.read()

        if existing_content == config_content:
            logger.info("NGINX hardening config (server_tokens) is unchanged. Skipping NGINX reload.")
            return True, ""

        logger.info(f"Generated NGINX hardening config for {HARDENING_CONF_PATH}, validating before apply...")
        return write_and_apply_configs({HARDENING_CONF_PATH: config_content})
    except Exception as e:
        logger.error(f"Failed to apply hardening settings: {e}")
        return False, str(e)


def apply_geo_block_settings(settings: dict) -> tuple[bool, str]:
    """
    Pushes the country allow/deny list into Redis for ml_check.lua to read —
    zero-reload, same pattern as apply_hardening_settings' IP whitelist/
    blacklist above. Requires GeoIP2 to actually be enabled (see
    apply_ddos_settings' geoip2 {} block generation) to have any effect;
    enforcement degrades to a no-op in ml_check.lua if
    $geoip2_data_country_code was never populated.
    """
    try:
        r = get_redis_client()
        enabled = settings.get("enabled", False)
        mode = settings.get("mode", "deny")
        countries = settings.get("countries", [])

        r.delete("waf:geo:countries")
        if enabled and mode in ("allow", "deny"):
            r.set("waf:geo:block_mode", mode)
            for code in countries:
                code = code.strip().upper()
                if code:
                    r.sadd("waf:geo:countries", code)
        else:
            r.set("waf:geo:block_mode", "disabled")

        logger.info(
            f"Successfully updated geo-block settings in Redis "
            f"(mode={mode if enabled else 'disabled'}, {len(countries)} countries)."
        )
        return True, ""
    except Exception as e:
        logger.error(f"Failed to apply geo-block settings: {e}")
        return False, str(e)


def apply_positive_security_settings(settings: dict) -> tuple[bool, str]:
    """
    Generates ModSecurity rules enforcing the Positive Security allowlist
    (allowed HTTP methods, allowed request Content-Types, restricted file
    extensions) and reloads to apply. Disabled by default — settings.get
    ("enabled") must be explicitly true, since these defaults (e.g.
    allowed_methods: GET/POST/HEAD only) would otherwise silently start
    rejecting any protected app that legitimately uses PUT/DELETE/PATCH the
    moment this feature shipped. When disabled, writes a comment-only file,
    which correctly removes any previously-active rules.

    Any of the three lists being empty just skips generating that specific
    check (not "block everything") — an accidentally-cleared field should
    degrade to "not enforced", not "deny all traffic".

    Scoping to protected-app traffic only (never the dashboard) is done by
    WHERE this file gets referenced (see POSITIVE_SECURITY_CONF_PATH's
    docstring above) — no skip rule needed here.
    """
    try:
        enabled = bool(settings.get("enabled", False))
        config_lines = [
            "# Auto-generated by CyberSentinel WAF GUI — Positive Security policy",
            "# Do not edit manually",
        ]

        if not enabled:
            config_lines.append("# Positive Security is currently disabled — no active rules.")
            config_content = "\n".join(config_lines) + "\n"
            logger.info("Positive Security is disabled — applying an empty policy.")
            return write_and_apply_configs({POSITIVE_SECURITY_CONF_PATH: config_content})

        allowed_methods = [m.strip().upper() for m in settings.get("allowed_methods", []) if m.strip()]
        allowed_content_types = [c.strip() for c in settings.get("allowed_content_types", []) if c.strip()]
        restricted_extensions = [e.strip().lower().lstrip(".") for e in settings.get("restricted_extensions", []) if e.strip()]

        config_lines.append("")

        if allowed_methods:
            method_pattern = "^(" + "|".join(re.escape(m) for m in allowed_methods) + ")$"
            config_lines.append(
                f'SecRule REQUEST_METHOD "!@rx {method_pattern}" '
                f'"id:5900002,phase:1,deny,status:405,log,'
                f"msg:'Method not allowed by Positive Security policy'\""
            )
            config_lines.append("")

        if allowed_content_types:
            ct_pattern = "^(" + "|".join(re.escape(c) for c in allowed_content_types) + ")"
            config_lines.append(
                'SecRule REQUEST_METHOD "@rx ^(POST|PUT|PATCH)$" '
                '"id:5900003,phase:1,chain,deny,status:415,log,'
                "msg:'Content-Type not allowed by Positive Security policy'\""
            )
            config_lines.append(
                f'    SecRule REQUEST_HEADERS:Content-Type "!@rx {ct_pattern}" ""'
            )
            config_lines.append("")

        if restricted_extensions:
            ext_pattern = r"\.(" + "|".join(re.escape(e) for e in restricted_extensions) + ")$"
            config_lines.append(
                f'SecRule REQUEST_FILENAME "@rx {ext_pattern}" '
                f'"id:5900004,phase:1,deny,status:403,log,t:lowercase,'
                f"msg:'Restricted file extension blocked by Positive Security policy'\""
            )
            config_lines.append("")
            # REQUEST_FILENAME above only ever matched the URL path (e.g.
            # GET /malware.exe) — a multipart file upload to an allowed
            # path (POST /upload with a part named shell.php) sailed
            # straight through, since the uploaded file's own name was
            # never checked. FILES_NAMES is ModSecurity's per-part
            # filename collection from multipart parsing (SecRequestBody
            # Access On, already set in modsecurity.conf) — populated
            # regardless of SecUploadDir, which only controls whether the
            # file's *content* gets persisted to disk (that's a separate,
            # not-yet-built capability — AV/malware scanning — not needed
            # just to read a filename). phase:2 because the request body
            # (where multipart parts live) isn't parsed yet at phase:1.
            config_lines.append(
                f'SecRule FILES_NAMES "@rx {ext_pattern}" '
                f'"id:5900005,phase:2,deny,status:403,log,t:lowercase,'
                f"msg:'Restricted file extension in uploaded file blocked by Positive Security policy'\""
            )
            config_lines.append("")

        config_content = "\n".join(config_lines) + "\n"
        logger.info(
            f"Generated Positive Security policy for {POSITIVE_SECURITY_CONF_PATH} "
            f"({len(allowed_methods)} allowed methods, {len(allowed_content_types)} allowed "
            f"content-types, {len(restricted_extensions)} restricted extensions), "
            "validating before apply..."
        )
        return write_and_apply_configs({POSITIVE_SECURITY_CONF_PATH: config_content})
    except Exception as e:
        logger.error(f"Failed to apply positive security settings: {e}")
        return False, str(e)


def apply_malware_scanning_settings(settings: dict) -> tuple[bool, str]:
    """
    Generates the @inspectFile SecRule (malware-scan.conf) AND its target
    script (malware-scan.sh) together, atomically, via one
    write_and_apply_configs() call — they must never drift out of sync
    (a .conf referencing a stale/missing script, or vice versa). Disabled
    by default: writes a comment-only .conf when settings["enabled"] is
    False, same convention as apply_positive_security_settings(), which
    correctly removes any previously-active rule.

    ModSecurity's SecUploadDir/SecUploadKeepFiles/SecUploadFileMode are
    static directives in modsecurity.conf (not toggle-driven — see that
    file's comment) — harmless when this feature is disabled, since
    nothing reads the uploaded-file temp path unless the @inspectFile
    rule generated here actually exists.

    The fail-open/fail-closed decision for a ClamAV-unreachable scan is
    baked directly into the generated script text (not read from a
    separate runtime config by the script itself) — see the fail_mode
    branch below. clamdscan's own exit-code convention: 0 = clean,
    1 = infected, 2 = scan error (can't connect, timed out, etc.) — only
    exit code 1 means "this file is actually infected"; anything else
    routes through the configured fail_mode instead of being treated as
    a detection.

    @inspectFile's own contract: the script's STDOUT is the match value —
    EMPTY stdout (regardless of exit code, though we always exit 0 on the
    non-match paths for clarity) means no match (upload allowed); ANY
    stdout content means the rule matches (upload blocked, logged with
    that text).
    """
    try:
        enabled = bool(settings.get("enabled", False))
        conf_lines = [
            "# Auto-generated by CyberSentinel WAF GUI — Malware Scanning policy (P1-10)",
            "# Do not edit manually",
        ]

        if not enabled:
            conf_lines.append("# Malware scanning is currently disabled — no active rules.")
            conf_content = "\n".join(conf_lines) + "\n"
            # No script needed while disabled, but write an inert placeholder
            # anyway rather than leaving a stale executable scanner script on
            # disk from a previous "enabled" state — matches "absence never
            # silently keeps old behavior alive" elsewhere in this codebase.
            script_content = (
                "#!/bin/sh\n"
                "# Malware scanning is disabled — this script should never be invoked\n"
                "# (no @inspectFile rule references it while disabled).\n"
                "exit 0\n"
            )
            logger.info("Malware scanning is disabled — applying an empty policy.")
            ok, err = write_and_apply_configs({
                MALWARE_SCAN_CONF_PATH: conf_content,
                MALWARE_SCAN_SCRIPT_PATH: script_content,
            })
            if ok:
                try:
                    # Standard rwxr-xr-x for a script ModSecurity's @inspectFile
                    # hook must be able to execute — not world-writable, contains no
                    # secrets.
                    os.chmod(MALWARE_SCAN_SCRIPT_PATH, 0o755)  # nosec B103
                except OSError as e:
                    logger.warning(f"Failed to chmod malware-scan.sh: {e}")
            return ok, err

        fail_mode = settings.get("fail_mode", "open")
        timeout_seconds = int(settings.get("scan_timeout_seconds", 5))

        if fail_mode == "closed":
            fallback_branch = (
                '        echo "AV scan unavailable (ClamAV unreachable or timed out) — '
                'blocked per fail-closed policy"\n'
                "        exit 1"
            )
        else:
            fallback_branch = (
                "        # ClamAV unreachable/timed out — fail OPEN per configured\n"
                "        # policy: allow the upload through rather than blocking every\n"
                "        # protected app's uploads during a scanner outage. Change to\n"
                "        # fail-closed in Settings > Hardening if this deployment needs\n"
                "        # the stricter guarantee instead.\n"
                "        exit 0"
            )

        script_content = (
            "#!/bin/sh\n"
            "# Auto-generated by CyberSentinel WAF GUI — ClamAV scan wrapper for\n"
            "# ModSecurity's @inspectFile operator (P1-10). Do not edit manually.\n"
            "#\n"
            "# Invoked by ModSecurity as: $0 <path-to-uploaded-file-part>\n"
            'FILE="$1"\n'
            "\n"
            f'RESULT=$(timeout {timeout_seconds} clamdscan --no-summary --infected --stream "$FILE" 2>/dev/null)\n'
            "STATUS=$?\n"
            "\n"
            'if [ "$STATUS" -eq 0 ]; then\n'
            "    exit 0\n"
            'elif [ "$STATUS" -eq 1 ]; then\n'
            '    echo "Malware detected: $RESULT"\n'
            "    exit 1\n"
            "else\n"
            f"{fallback_branch}\n"
            "fi\n"
        )

        conf_lines.extend([
            "",
            f'SecRule FILES_TMPNAMES "@inspectFile {MALWARE_SCAN_SCRIPT_PATH}" '
            f'"id:5910001,phase:2,block,t:none,log,'
            f"msg:'Malware detected in uploaded file (ClamAV)',severity:'CRITICAL',"
            f"tag:'malware',tag:'av-scan'\"",
            "",
        ])
        conf_content = "\n".join(conf_lines) + "\n"

        logger.info(
            f"Generated malware-scanning policy for {MALWARE_SCAN_CONF_PATH} "
            f"(fail_mode={fail_mode}, timeout={timeout_seconds}s), validating before apply..."
        )
        ok, err = write_and_apply_configs({
            MALWARE_SCAN_CONF_PATH: conf_content,
            MALWARE_SCAN_SCRIPT_PATH: script_content,
        })
        if ok:
            try:
                # See the other chmod(..., 0o755) above for why this is fine.
                os.chmod(MALWARE_SCAN_SCRIPT_PATH, 0o755)  # nosec B103
            except OSError as e:
                logger.warning(f"Failed to chmod malware-scan.sh: {e}")
        return ok, err
    except Exception as e:
        logger.error(f"Failed to apply malware scanning settings: {e}")
        return False, str(e)


def apply_api_schema_settings(domain: str, api_schema_json: str, mode: str) -> tuple[bool, str]:
    """
    Pushes one protected app's positive-security API schema into Redis —
    zero-reload, same pattern as apply_hardening_settings/apply_geo_block_
    settings above. Keyed by domain (not app_id) because that's what
    ml_check.lua's schema_validate module has cheaply available at request
    time via $host, with no need for an app_id lookup from Lua.

    api_schema_json is expected to already be validated JSON (see
    routes/apps.py's schema endpoint) shaped like:
        {"endpoints": [{"method": "POST", "path": "/api/users",
                         "required_fields": [...], "allowed_fields": [...]}]}
    A None/empty api_schema_json clears the key — enforcement in Lua is a
    no-op whenever nothing is stored for a given host, matching Positive
    Security's "absence never means deny-all" convention.
    """
    try:
        r = get_redis_client()
        key = f"waf:schema:{domain.strip().lower()}"
        if not api_schema_json:
            r.delete(key)
            logger.info(f"Cleared API schema for domain '{domain}'.")
            return True, ""

        import json as _json
        stored = _json.dumps({"mode": mode, **_json.loads(api_schema_json)})
        r.set(key, stored)
        logger.info(f"Successfully updated API schema in Redis for domain '{domain}' (mode={mode}).")
        return True, ""
    except Exception as e:
        logger.error(f"Failed to apply API schema settings for domain '{domain}': {e}")
        return False, str(e)


def apply_custom_response_page(html_content: str) -> tuple[bool, str]:
    """
    Writes the admin-configured "WAF blocked you" page to
    CUSTOM_RESPONSE_PAGE_PATH. The file itself is inert until a protected
    app's server{} block references it via an `internal` location (added in
    sync_protected_apps_to_nginx()) — that's what makes this actually get
    served on a real 403 instead of just sitting on disk.

    Uses write_and_apply_configs() purely for the atomic-write + validate +
    reload guarantee every other config writer here gets, even though nginx
    syntax validation has nothing to check in a plain HTML file — the value
    is the same backup/rollback-on-failure behavior and cache-busting reload.
    """
    try:
        return write_and_apply_configs({CUSTOM_RESPONSE_PAGE_PATH: html_content})
    except Exception as e:
        logger.error(f"Failed to apply custom response page: {e}")
        return False, str(e)


