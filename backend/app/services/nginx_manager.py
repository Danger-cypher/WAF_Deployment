def _get_redis_password() -> str:
    """
    Reads the Redis authentication password from a protected secret file.
    Falls back to empty string (no auth) if the file does not exist.
    """
    try:
        with open(REDIS_SECRET_FILE, "r") as f:
            return f.read().strip()
    except FileNotFoundError:
        logger.warning(
            f"Redis secret file not found at {REDIS_SECRET_FILE}. "
            "Connecting without authentication."
        )
        return ""
    except Exception as e:
        logger.error(f"Failed to read Redis secret file: {e}")
        return ""


def _sanitize_nginx_pattern(value: str) -> str:
    """
    Strips characters that would break NGINX map block structure or allow
    arbitrary directive injection via user-supplied rate limiting patterns.
    Removes: { } ; newlines and carriage returns.
    """
    return re.sub(r'[{};\'"\n\r]', '', value)


def _validate_ip_or_cidr(ip: str) -> bool:
    """
    Validates that a string is a valid IPv4/IPv6 address or CIDR network.
    Returns True if valid, False otherwise.
    """
    try:
        ipaddress.ip_network(ip.strip(), strict=False)
        return True
    except ValueError:
        return False


# JA4's fixed a_b_c shape (see ml-waf/ja4_core.lua's part_a/part_b/part_c):
# a 10-char part A (protocol+version+sni+cipher_count+ext_count+alpn),
# then two 12-char lowercase-hex SHA-256-truncated parts. This is a shape
# check only, not proof the fingerprint corresponds to any real client an
# admin has actually observed — they may be pasting one in from an
# external threat-intel source rather than one this WAF captured itself.
_JA4_RE = re.compile(r"^[a-z0-9]{10}_[0-9a-f]{12}_[0-9a-f]{12}$")


def _validate_ja4(fingerprint: str) -> bool:
    """Validates that a string matches JA4's fixed format. Returns True if
    valid, False otherwise."""
    return bool(_JA4_RE.match(fingerprint.strip().lower()))


def _atomic_write(path: str, content: str) -> None:
    """
    Writes `content` to `path` via temp file + os.replace() so a crash or
    power loss mid-write can never leave a truncated/corrupt config file on
    disk — same pattern as rule_manager's override-file writer.
    """
    directory = os.path.dirname(path)
    os.makedirs(directory, exist_ok=True)
    fd, tmp_path = tempfile.mkstemp(dir=directory, prefix=".nginxcfg-", suffix=".tmp")
    try:
        # mkstemp() creates the file at mode 0600 (owner read/write only) and
        # os.replace() carries that mode over — nginx configs need to stay
        # world-readable like the files they replace, or OpenResty running as
        # a different uid (or any non-root debugging/backup tooling on the
        # host) silently loses the ability to read its own config.
        os.chmod(tmp_path, 0o644)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(content)
        os.replace(tmp_path, path)
    except Exception:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)
        raise


def write_and_apply_configs(file_contents: dict) -> tuple[bool, str]:
    """
    Writes one or more generated NGINX config files, validates the *full*
    config syntax with test_nginx_config(), and only reloads if it's valid —
    restoring every file to its prior state (or deleting it, if it didn't
    exist before) on failure.

    This matters because `nginx -s reload`'s exit code only reflects whether
    the running master process could be *signaled*, not whether it accepted
    the new config: nginx re-validates asynchronously inside the master
    after the reload command has already returned, so a caller that trusts
    reload_nginx()'s return value alone can silently believe a bad config
    was applied when nginx actually rejected it and kept running the old
    one. Callers should surface the returned message to the admin instead
    of a generic "failed" — it's the actual nginx config test output.
    """
    backups = {}
    try:
        for path, content in file_contents.items():
            if os.path.exists(path):
                with open(path, "r", encoding="utf-8") as f:
                    backups[path] = f.read()
            else:
                backups[path] = None
            _atomic_write(path, content)
    except Exception as e:
        logger.error(f"Failed to write NGINX config file(s): {e}")
        return False, f"Failed to write configuration file(s): {e}"

    valid, err_msg = test_nginx_config()
    if not valid:
        for path, old_content in backups.items():
            try:
                if old_content is None:
                    if os.path.exists(path):
                        os.remove(path)
                else:
                    _atomic_write(path, old_content)
            except Exception as restore_err:
                logger.error(f"Failed to restore {path} after invalid config: {restore_err}")
        logger.error(f"NGINX config validation failed, changes rolled back: {err_msg}")
        return False, f"NGINX configuration validation failed (changes rolled back): {err_msg}"

    if not reload_nginx():
        return False, "NGINX configuration is valid but the reload command failed. Check system permissions and sudoers/docker exec access."

    return True, ""


def apply_ddos_settings(settings: dict) -> tuple[bool, str]:
    """
    Generates NGINX rate-limiting configuration based on the provided settings
    and reloads NGINX to apply them.
    """
    try:
        rate_limit_rps = settings.get("rate_limit_rps", 50)
        burst_tolerance = settings.get("burst_tolerance", 100)
        trusted_ips = settings.get("trusted_ips", [])
        bot_action = settings.get("bot_mitigation_action", "Silent Drop")
        advanced_rules = settings.get("advanced_rules", [])

        # General rate-limit zones (waf_ddos_req/waf_ddos_conn below, and
        # every zone that inherits limit_req_status/limit_conn_status from
        # http level because it doesn't declare its own — login_limit,
        # api_limit, ws_conn_limit on the console, every generated app's
        # zone_app_<id>) ALWAYS return 429. This used to be `status_code =
        # 444 if bot_action == "Silent Drop" else 429`, applied globally —
        # but limit_req_status/limit_conn_status are single, shared-per-
        # scope directives, not per-zone, so the bot-mitigation dropdown
        # (meant only to control how confirmed-bad-bot-UA traffic gets
        # handled) was silently overriding the status for EVERY unrelated
        # rate limit in the product too: a legitimate client tripping the
        # login rate limiter, or any customer app's own API rate limit,
        # got a silently-closed connection with no Retry-After the moment
        # an admin picked "Silent Drop" for bots (audit finding P2-07).
        GENERAL_RATE_LIMIT_STATUS = 429

        # Bad-bot-UA traffic (the map below) is no longer rate-limited via
        # a native nginx zone at all — that's what made it share a status
        # with the general zones above in the first place. It's now
        # enforced in Lua instead (ml_check.lua's check_bad_bot_rate_limit,
        # mirroring check_adaptive_throttle's Redis INCR+EXPIRE pattern),
        # which can exit with whichever status THIS setting says without
        # touching any other zone. 0 means "don't apply this check at
        # all" — JS Challenge mode already has its own mechanism below.
        if bot_action == "Silent Drop":
            bot_mitigation_status_code = 444
        elif bot_action == "Block":
            bot_mitigation_status_code = 429
        else:
            bot_mitigation_status_code = 0

        # JS Challenge: instead of an outright reject, bad-UA-matching traffic
        # gets an interstitial (ml-waf/bot_challenge.lua) that a real browser's
        # JS clears itself; a scripted client never does. That flow needs at
        # least two requests from the same client in quick succession (the
        # initial hit + the JS-triggered reload), so
        # check_bad_bot_rate_limit() (1r/m, effectively "block after the
        # first request") must NOT also apply, or the reload itself gets
        # rejected before Lua's bot_challenge.check() ever sees it —
        # bot_mitigation_status_code is 0 for this mode for exactly that
        # reason (see where it's set above).
        bot_challenge_enabled = bot_action == "JS Challenge"

        config_lines = [
            "# Auto-generated by CyberSentinel WAF GUI",
            "# Do not edit manually",
            "",
        ]

        # Mirror of every limit_req this function emits at http level, in a
        # form each proxying location includes so the zones actually evaluate.
        # See DDOS_LIMITS_INCLUDE_PATH for why this duplication is required.
        location_limit_lines = [
            "# Auto-generated by CyberSentinel WAF GUI — DDoS/bot rate limits",
            "# Do not edit manually. Included from inside each proxying location,",
            "# so these zones apply IN ADDITION to that location's own limit_req,",
            "# which would otherwise replace them outright (nginx does not merge",
            "# limit_req across levels). See nginx_manager.DDOS_LIMITS_INCLUDE_PATH.",
            "",
        ]

        # Define GeoIP2 databases if they exist on disk AND the geoip2 nginx module is loaded.
        # GEOIP_DATA_DIR env var allows portable deployment on client servers.
        # Falls back to the demo-server absolute path when env var is not set.
        # GEOIP2_MODULE_ENABLED must be set to "true" once OpenResty is rebuilt with the module.
        geoip2_module_enabled = os.environ.get("GEOIP2_MODULE_ENABLED", "false").lower() == "true"

        _geoip_dir = os.environ.get(
            "GEOIP_DATA_DIR",
            os.path.abspath(
                os.path.join(os.path.dirname(os.path.dirname(__file__)), "data")
            )
        )
        COUNTRY_DB = os.path.join(_geoip_dir, "GeoLite2-Country.mmdb")
        ASN_DB = os.path.join(_geoip_dir, "GeoLite2-ASN.mmdb")

        has_country_db = os.path.exists(COUNTRY_DB)
        has_asn_db = os.path.exists(ASN_DB)

        if geoip2_module_enabled and has_country_db:
            config_lines.append(f"geoip2 {COUNTRY_DB} {{")
            config_lines.append(
                "    $geoip2_data_country_code source=$remote_addr country iso_code;"
            )
            config_lines.append("}")
            config_lines.append("")
        elif has_country_db:
            config_lines.append(
                "# geoip2 module not loaded — set GEOIP2_MODULE_ENABLED=true after rebuilding OpenResty"
            )
            config_lines.append("")

        if geoip2_module_enabled and has_asn_db:
            config_lines.append(f"geoip2 {ASN_DB} {{")
            config_lines.append(
                "    $geoip2_data_asn source=$remote_addr autonomous_system_number;"
            )
            config_lines.append(
                "    $geoip2_data_org source=$remote_addr autonomous_system_organization;"
            )
            config_lines.append("}")
            config_lines.append("")

        # --- Bot Mitigation ---
        config_lines.append("# --- Bot Mitigation ---")
        config_lines.append("map $http_user_agent $is_bad_bot {")
        config_lines.append("    default 0;")
        # Malicious crawlers & scrapers
        config_lines.append('    "~*semrush" 1;')
        config_lines.append('    "~*ahrefs" 1;')
        config_lines.append('    "~*mj12bot" 1;')
        config_lines.append('    "~*dotbot" 1;')
        config_lines.append('    "~*rogerbot" 1;')
        config_lines.append('    "~*megaindex" 1;')
        config_lines.append('    "~*zoominfobot" 1;')
        config_lines.append('    "~*yandexbot" 1;')
        config_lines.append('    "~*baiduspider" 1;')
        config_lines.append('    "~*screaming frog" 1;')
        # Vulnerability scanners & tools
        config_lines.append('    "~*sqlmap" 1;')
        config_lines.append('    "~*nmap" 1;')
        config_lines.append('    "~*nikto" 1;')
        config_lines.append('    "~*dirbuster" 1;')
        config_lines.append('    "~*censys" 1;')
        config_lines.append('    "~*shodan" 1;')
        config_lines.append('    "~*netsparker" 1;')
        config_lines.append('    "~*acunetix" 1;')
        # Common HTTP client libraries used for botting
        config_lines.append('    "~*python-requests" 1;')
        config_lines.append('    "~*pycurl" 1;')
        config_lines.append('    "~*urllib" 1;')
        config_lines.append('    "~*wget" 1;')
        # Empty user-agent or standard hyphen
        config_lines.append('    "-" 1;')
        config_lines.append('    "" 1;')
        config_lines.append("}")
        config_lines.append("")
        # Bad-bot-UA traffic used to get its own limit_req_zone here (keyed
        # by client IP, 1r/m) — moved to ml_check.lua's
        # check_bad_bot_rate_limit() instead (see GENERAL_RATE_LIMIT_STATUS
        # above for why: it shared a status code with every other rate
        # limit in the product). $is_bad_bot above still drives it, just
        # read directly as an nginx variable from Lua rather than through a
        # dedicated zone.

        # We always define the $limit_key variable.
        # If trusted_ips exist, it is dynamic. If not, it is equivalent to $binary_remote_addr.
        if trusted_ips:
            config_lines.append("geo $limit {")
            config_lines.append("    default 1;")
            for ip in trusted_ips:
                ip = ip.strip()
                if ip:
                    if not _validate_ip_or_cidr(ip):
                        logger.warning(f"Skipping invalid IP/CIDR in trusted list: '{ip}'")
                        continue
                    config_lines.append(f"    {ip} 0;")
            config_lines.append("}")
            config_lines.append("")
            config_lines.append("map $limit $limit_key {")
            config_lines.append('    0 "";')
            config_lines.append("    1 $binary_remote_addr;")
            config_lines.append("}")
        else:
            config_lines.append("map $host $limit_key {")
            config_lines.append("    default $binary_remote_addr;")
            config_lines.append("}")

        config_lines.append("")
        zone_key = "$limit_key"

        config_lines.append(
            f"limit_req_zone {zone_key} zone=waf_ddos_req:10m rate={rate_limit_rps}r/s;"
        )
        config_lines.append(f"limit_req_status {GENERAL_RATE_LIMIT_STATUS};")
        config_lines.append("")
        # These two http-level limit_req directives are a FALLBACK ONLY, for
        # locations that declare no limit_req of their own.
        #
        # nginx does not merge limit_req across configuration levels: a
        # location containing any limit_req directive REPLACES every
        # inherited one rather than adding to it. Every proxying location in
        # this product declares its own (zone_app_<id> in the generated app
        # vhosts, api_limit/login_limit in the console vhost), so these
        # http-level lines applied to essentially no real traffic at all.
        #
        # Confirmed live before the fix: four consecutive requests with
        # User-Agent "Wget/1.21" — which the map above classifies as a bad
        # bot, against a zone rated 1r/m with burst=1 — all returned 200.
        # The entire DDoS & Bot Shield page was configuring zones that never
        # evaluated a request while presenting as active (audit finding
        # P1-04). The per-location half of the fix is DDOS_LIMITS_INCLUDE_PATH
        # below, which every generated location now includes.
        config_lines.append(
            f"limit_req zone=waf_ddos_req burst={burst_tolerance} nodelay;"
        )
        location_limit_lines.append(
            f"limit_req zone=waf_ddos_req burst={burst_tolerance} nodelay;"
        )
        config_lines.append("")

        # Config-time boolean exposed as a runtime nginx variable so
        # bot_challenge.lua knows whether this mode is active — "map $host"
        # with only a default entry ignores $host entirely and just always
        # yields the same baked-in value (a standard nginx trick for
        # injecting a Python-decided constant into the request-variable
        # namespace Lua can read).
        config_lines.append(f"map $host $waf_bot_challenge_enabled {{")
        config_lines.append(f"    default {1 if bot_challenge_enabled else 0};")
        config_lines.append("}")
        config_lines.append("")

        # Same trick, carrying the status ml_check.lua's
        # check_bad_bot_rate_limit() should exit with for a rate-limited
        # bad-bot request — 444 (Silent Drop), 429 (Block), or 0 (JS
        # Challenge / any other mode — don't apply this check at all).
        # This is what lets that check use a different status than every
        # other rate limit in the product without them sharing a
        # limit_req_status scope (see GENERAL_RATE_LIMIT_STATUS above).
        config_lines.append(f"map $host $waf_bot_mitigation_status {{")
        config_lines.append(f"    default {bot_mitigation_status_code};")
        config_lines.append("}")
        config_lines.append("")

        # Independent toggle for the same challenge mechanism, triggered by
        # ml_server.py's X-WAF-Risk-Challenge response header (threat_score's
        # "log" band) instead of the bad-bot UA signal above. No interaction
        # with the bad-bot rate limit above — this path never touches it.
        risk_challenge_enabled = settings.get("risk_challenge_enabled", False)
        config_lines.append(f"map $host $waf_risk_challenge_enabled {{")
        config_lines.append(f"    default {1 if risk_challenge_enabled else 0};")
        config_lines.append("}")
        config_lines.append("")

        # Independent toggle: a tighter, Lua/Redis-enforced rate check for
        # IPs whose reputation (rep:{ip}, written by ml_server.py on
        # confirmed blocks) has crossed a threshold — layered on top of,
        # never replacing, the native limit_req zones below, which must
        # keep working even when Redis/ML are degraded. See ml_check.lua's
        # check_adaptive_throttle().
        adaptive_throttle_enabled = settings.get("adaptive_throttle_enabled", False)
        config_lines.append(f"map $host $waf_adaptive_throttle_enabled {{")
        config_lines.append(f"    default {1 if adaptive_throttle_enabled else 0};")
        config_lines.append("}")
        config_lines.append("")

        # API sequential-enumeration detection toggle — see enum_detect.lua.
        # Same $host-keyed map shape as adaptive_throttle_enabled just
        # above (it's a plain settings field on this same ddos-bot dict,
        # unlike good_bot_enabled below which lives in its own namespace).
        api_enum_protection_enabled = settings.get("api_enum_protection_enabled", False)
        config_lines.append(f"map $host $waf_api_enum_enabled {{")
        config_lines.append(f"    default {1 if api_enum_protection_enabled else 0};")
        config_lines.append("}")
        config_lines.append("")

        # Verified-good-bot allowlist toggle (Settings > Hardening ->
        # good_bot_service.py) — its own settings namespace, not part of
        # the ddos-bot `settings` dict passed into this function, so it's
        # read directly rather than threaded through as a parameter.
        # Read here (not in ml_check.lua) so the check is a zero-cost `if`
        # on an nginx variable when disabled, same pattern as every other
        # toggle in this block, rather than a Redis round-trip per request
        # to find out the feature is off.
        from app.services.settings_manager import settings_manager as _settings_manager
        good_bot_enabled = _settings_manager.get_good_bots().get("enabled", False)
        config_lines.append(f"map $host $waf_good_bot_enabled {{")
        config_lines.append(f"    default {1 if good_bot_enabled else 0};")
        config_lines.append("}")
        config_lines.append("")

        # Connection limiting
        config_lines.append(f"limit_conn_zone {zone_key} zone=waf_ddos_conn:10m;")
        config_lines.append(f"limit_conn_status {GENERAL_RATE_LIMIT_STATUS};")
        config_lines.append(
            "limit_conn waf_ddos_conn 100;"
        )  # Hardcoded max 100 connections per IP for now
        config_lines.append("")

        # --- Advanced Rate Limiting Rules ---
        if advanced_rules:
            config_lines.append("# --- Advanced Rate Limiting Rules ---")
            for rule in advanced_rules:
                if not rule.get("enabled", True):
                    continue
                rule_id = rule.get("id")
                rule_name = rule.get("name", f"Rule {rule_id}")
                param_type = rule.get("parameter_type", "URI")
                param_value = rule.get("parameter_value", "")
                rule_rps = rule.get("rate_limit_rps", 10)
                rule_burst = rule.get("burst_tolerance", 20)

                # Determine NGINX variable to inspect and whether to rate-limit by the value itself
                nginx_var = "$request_uri"
                limit_by_value = False
                if param_type == "URI":
                    nginx_var = "$request_uri"
                elif param_type == "Host+URI":
                    # Plain "URI" rules match $request_uri alone, which is
                    # shared across every vhost this gateway proxies — a rule
                    # for "/login" would rate-limit that path on EVERY
                    # protected app, not just the one it was meant for.
                    # Host+URI scopes the match to one specific app's domain
                    # (used by the per-app login/brute-force protection
                    # feature in ProtectedApps.jsx).
                    nginx_var = "$host$request_uri"
                elif param_type == "Method":
                    nginx_var = "$request_method"
                elif param_type == "Referrer":
                    nginx_var = "$http_referer"
                elif param_type == "Content-Type":
                    nginx_var = "$http_content_type"
                elif param_type == "IP":
                    nginx_var = "$remote_addr"
                elif param_type == "Session":
                    # cookie_name comes straight from the admin-supplied rule
                    # payload with no character restriction — embedded raw
                    # into an nginx variable-name token, an unsanitized value
                    # containing e.g. a newline or `{` could break out of the
                    # generated map block into arbitrary config injection.
                    cookie_name = param_value.strip() or "session"
                    safe_cookie_name = re.sub(r"[^A-Za-z0-9_-]", "", cookie_name).lower().replace("-", "_")
                    if not safe_cookie_name:
                        logger.warning(f"Skipping rule '{rule_name}': cookie name is empty after sanitization.")
                        continue
                    nginx_var = f"$cookie_{safe_cookie_name}"
                    limit_by_value = True
                elif param_type == "Country":
                    if not geoip2_module_enabled or not has_country_db:
                        logger.warning(
                            f"Skipping Country rate limiting rule '{rule_name}' — geoip2 module not enabled or Country GeoIP DB missing."
                        )
                        continue
                    nginx_var = "$geoip2_data_country_code"
                elif param_type == "ISP/ASN":
                    if not geoip2_module_enabled or not has_asn_db:
                        logger.warning(
                            f"Skipping ISP/ASN rate limiting rule '{rule_name}' — geoip2 module not enabled or ASN GeoIP DB missing."
                        )
                        continue
                    # Match ASN (if numeric) or Org name
                    if param_value.strip().isdigit():
                        nginx_var = "$geoip2_data_asn"
                    else:
                        nginx_var = "$geoip2_data_org"
                elif param_type == "Header":
                    # Custom header parsing (e.g. "X-API-Key: value" or just "X-API-Key")
                    # Same raw-embedding risk as the Session/cookie case above —
                    # header_name is sanitized to a safe variable-name charset
                    # before being spliced into the generated $http_<name> token.
                    if ":" in param_value:
                        parts = param_value.split(":", 1)
                        header_name = parts[0].strip()
                        param_value = parts[1].strip()
                    else:
                        header_name = param_value.strip()
                        limit_by_value = True

                    safe_header_name = re.sub(r"[^A-Za-z0-9_-]", "", header_name).lower().replace("-", "_")
                    if not safe_header_name:
                        logger.warning(f"Skipping rule '{rule_name}': header name is empty after sanitization.")
                        continue
                    nginx_var = "$http_" + safe_header_name

                if limit_by_value:
                    config_lines.append(
                        f"# Rule: {rule_name} (Type: {param_type}, Limit by unique value of {nginx_var})"
                    )
                    config_lines.append(f"map {nginx_var} $limit_key_{rule_id} {{")
                    config_lines.append(f'    "~.+" {nginx_var};')
                    config_lines.append('    default "";')
                    config_lines.append("}")
                else:
                    # Sanitize pattern to prevent NGINX config injection
                    # Strip characters that can break NGINX map block structure
                    clean_value = _sanitize_nginx_pattern(param_value)
                    if not clean_value:
                        logger.warning(f"Skipping rule '{rule_name}': pattern is empty after sanitization.")
                        continue

                    config_lines.append(
                        f"# Rule: {rule_name} (Type: {param_type}, Match: {param_value})"
                    )
                    config_lines.append(f"map {nginx_var} $limit_key_{rule_id} {{")
                    # Map to $limit_key (so trusted IPs automatically bypass this check)
                    # If param_type is Country, IP, Host+URI, or numeric ISP/ASN, anchor
                    # matching with ^...$ to prevent substring matching
                    if param_type in ("Country", "IP", "Host+URI") or (param_type == "ISP/ASN" and param_value.strip().isdigit()):
                        config_lines.append(f'    "~*^{clean_value}$" {zone_key};')
                    else:
                        config_lines.append(f'    "~*{clean_value}" {zone_key};')
                    config_lines.append('    default "";')
                    config_lines.append("}")

                # Rate expressed per-second by default; per-minute is available
                # for rules needing finer granularity than an integer r/s
                # allows (e.g. login/brute-force protection — "5 attempts per
                # minute" has no clean r/s equivalent below 1r/s=60/min).
                rate_unit = rule.get("rate_limit_unit", "r/s")
                if rate_unit not in ("r/s", "r/m"):
                    rate_unit = "r/s"
                config_lines.append(
                    f"limit_req_zone $limit_key_{rule_id} zone=zone_{rule_id}:10m rate={rule_rps}{rate_unit};"
                )
                config_lines.append(
                    f"limit_req zone=zone_{rule_id} burst={rule_burst} nodelay;"
                )
                # Advanced rules were overridden at http level for exactly the
                # same reason as the two zones above — an admin's custom
                # per-country/per-ISP/per-header rule never fired either.
                location_limit_lines.append(
                    f"limit_req zone=zone_{rule_id} burst={rule_burst} nodelay;"
                )
                config_lines.append("")

        config_content = "\n".join(config_lines) + "\n"
        location_limits_content = "\n".join(location_limit_lines) + "\n"

        logger.info(f"Generated NGINX DDoS config for {DDOS_CONF_PATH}, validating before apply...")

        # Validate + apply + reload (rolls back BOTH files if the new config
        # is invalid — they must move together, since the .inc references
        # zones declared in waf_ddos.conf).
        return write_and_apply_configs({
            DDOS_CONF_PATH: config_content,
            DDOS_LIMITS_INCLUDE_PATH: location_limits_content,
        })

    except Exception as e:
        logger.error(f"Failed to apply DDoS settings: {e}")
        return False, str(e)


def reload_nginx() -> bool:
    """
    Reloads the NGINX/OpenResty service gracefully.
    Tries sudo-prefixed commands first (required when running as non-root service user).
    Falls back to direct execution if sudo is not available.
    Requires /etc/sudoers.d/cybersentinel-waf to grant NOPASSWD for these commands.
    """
    candidates = [
        # Docker reload variants (first check if running in docker-compose environment)
        ["docker", "exec", "waf-openresty", "openresty", "-c", "/etc/nginx/nginx.conf", "-s", "reload"],
        ["docker", "exec", "waf-openresty", "nginx", "-c", "/etc/nginx/nginx.conf", "-s", "reload"],
        # sudo variants (for non-root service user via sudoers grant)
        ["sudo", "/usr/local/openresty/bin/openresty", "-c", "/etc/nginx/nginx.conf", "-s", "reload"],
        ["sudo", "/usr/local/openresty/nginx/sbin/nginx", "-c", "/etc/nginx/nginx.conf", "-s", "reload"],
        # Direct variants (when running as root)
        ["/usr/local/openresty/bin/openresty", "-c", "/etc/nginx/nginx.conf", "-s", "reload"],
        ["/usr/local/openresty/nginx/sbin/nginx", "-c", "/etc/nginx/nginx.conf", "-s", "reload"],
        ["openresty", "-c", "/etc/nginx/nginx.conf", "-s", "reload"],
        ["nginx", "-c", "/etc/nginx/nginx.conf", "-s", "reload"],
    ]
    for cmd in candidates:
        try:
            result = subprocess.run(
                cmd, capture_output=True, text=True, timeout=10  # nosec B603
            )
            if result.returncode == 0:
                logger.info(f"NGINX/OpenResty reloaded successfully via: {' '.join(cmd)}")
                return True
            else:
                logger.warning(
                    f"Reload via '{' '.join(cmd)}' failed (rc={result.returncode}): "
                    f"{result.stderr.strip()}"
                )
        except FileNotFoundError:
            logger.debug(f"Command not found: {cmd[0]}, trying next...")
            continue
        except subprocess.TimeoutExpired:
            logger.error(f"Reload command timed out: {' '.join(cmd)}")
            continue
        except Exception as e:
            logger.error(f"Error reloading via '{' '.join(cmd)}': {e}")
            continue
    logger.error("All NGINX/OpenResty reload attempts exhausted. Check sudoers and binary paths.")
    return False


